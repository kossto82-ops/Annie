"""Curiosity — deciding what to wonder about, voicing tensions, pursuing impulses.

Curiosity is self-generated by evaluating the self-model, companion model,
contested beliefs, load-bearing observations, recurring goals, capability
needs, and meta-knowledge (Vision §16).  The impulse it raises is a
recommendation, not an action.
"""

